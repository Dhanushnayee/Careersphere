"""
CareerSphere AI — AI Resume Analysis Models
Phase 1 Foundation
"""
import uuid
from django.db import models
from apps.resumes.models import ResumeDocument


class ResumeAnalysisResult(models.Model):
    """
    Stores structured outputs generated by the AI Resume Copilot.
    Captures ATS compatibility, missing skill keywords, and bullet recommendations.
    """
    id = models.BigAutoField(primary_key=True)
    uuid = models.UUIDField(default=uuid.uuid4, editable=False, unique=True, db_index=True)
    resume = models.ForeignKey(
        ResumeDocument,
        on_delete=models.CASCADE,
        related_name="analysis_results",
    )
    target_job_title = models.CharField(max_length=255, blank=True)
    ats_score = models.PositiveSmallIntegerField(
        help_text="Standardized ATS compatibility percentage (0-100)",
        default=0,
    )
    quantification_score = models.PositiveSmallIntegerField(
        help_text="Metric & outcome presence score (0-100)",
        default=0,
    )
    bullet_relevance_score = models.PositiveSmallIntegerField(
        help_text="Target role alignment score (0-100)",
        default=0,
    )
    strengths = models.JSONField(default=list, help_text="List of verified strengths")
    improvements = models.JSONField(default=list, help_text="Actionable bullet points to improve")
    missing_skills = models.JSONField(default=list, help_text="Key keywords absent from the resume")
    matched_skills = models.JSONField(default=list, help_text="Identified matching competencies")
    model_version = models.CharField(max_length=50, default="gemini-2.5-flash")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Resume Analysis Result"
        verbose_name_plural = "Resume Analysis Results"
        ordering = ["-created_at"]

    def __str__(self):
        return f"Analysis for {self.resume.title} (ATS: {self.ats_score}%)"
